import { z } from "zod";
import {
  assertSameOrigin,
  clientKey,
  fail,
  ok,
  parseBody,
  rateLimit,
  unauthorized,
} from "@/lib/http";
import { currentUser } from "@/lib/auth/session";
import { listCertificates } from "@/lib/db/queries";
import { issueCertificate, CertificateError } from "@/lib/certificates/service";
import { parseCertificatePayload } from "@/lib/certificates/sign";
import { hederaStatus } from "@/lib/hedera/config";

export const dynamic = "force-dynamic";

const issueSchema = z.object({
  skillId: z.string().min(1).max(60),
});

export async function GET() {
  const user = await currentUser();
  if (!user) return unauthorized();

  const certificates = listCertificates(user.id).map((certificate) => {
    const payload = parseCertificatePayload(certificate.payload);
    return {
      id: certificate.id,
      skillId: certificate.skillId,
      skillName: payload?.claim.skillName ?? certificate.skillId,
      estimate: payload?.claim.estimate ?? null,
      confidence: payload?.claim.confidence ?? null,
      status: certificate.status,
      anchorStatus: certificate.anchorStatus,
      anchorTopicId: certificate.anchorTopicId,
      anchorSequence: certificate.anchorSequence,
      createdAt: certificate.createdAt,
    };
  });

  return ok({ certificates, hedera: hederaStatus() });
}

export async function POST(request: Request) {
  if (!(await assertSameOrigin())) {
    return fail("bad_origin", "Request rejected: origin mismatch.", 403);
  }
  const user = await currentUser();
  if (!user) return unauthorized();
  if (!user.profile.onboardingComplete) {
    return fail("onboarding_incomplete", "Finish onboarding before issuing a certificate.", 409);
  }

  const key = await clientKey("certificates");
  if (!rateLimit(`${key}:${user.id}`, 10, 3_600_000)) {
    return fail("rate_limited", "Certificate issuance is limited to 10 per hour.", 429);
  }

  const { data, error } = await parseBody(request, issueSchema);
  if (error) return error;

  try {
    const result = await issueCertificate(user.id, data.skillId);
    return ok(
      {
        id: result.certificate.id,
        pdfUnavailable: true,
        certificate: {
          id: result.certificate.id,
          payloadHash: result.certificate.payloadHash,
          signature: result.certificate.signature,
          keyId: result.certificate.keyId,
          anchorStatus: result.certificate.anchorStatus,
          createdAt: result.certificate.createdAt,
        },
        payload: result.payload,
        anchor: result.anchor,
        publicUrl: result.publicUrl,
        note:
          "The certificate is a signed JSON document. A PDF rendering is not generated by this MVP; download the JSON and verify the signature against the published key.",
      },
      201,
    );
  } catch (cause) {
    if (cause instanceof CertificateError) {
      return fail(cause.code, cause.message, cause.code === "not_found" ? 404 : 409);
    }
    return fail("certificate_failed", "The certificate could not be issued.", 500);
  }
}
